#!/usr/bin/env python3
"""Validate redistributable archive contents and reject build-machine path leaks."""
from pathlib import Path
import re
import sys
import zipfile
allowed={
 'Contents/Info.plist','Contents/MacOS/FanatecGFN','Contents/Resources/FFBReceiver',
 'Contents/Resources/FanatecBridge.dylib','Contents/Resources/AppIcon.icns',
 'Contents/Resources/LICENSE','Contents/Resources/THIRD_PARTY_NOTICES.md',
 'Contents/_CodeSignature/CodeResources',
}
for archive in sys.argv[1:]:
    seen=set()
    with zipfile.ZipFile(archive) as z:
        for item in z.infolist():
            if item.is_dir():continue
            # AppleDouble resource metadata generated by ditto is permitted.
            if item.filename.startswith('__MACOSX/'):continue
            prefix='Fanatec GFN.app/'
            assert item.filename.startswith(prefix), item.filename
            path=item.filename[len(prefix):]
            assert path in allowed, 'Unexpected bundled file: '+path
            data=z.read(item)
            assert not re.search(rb'/Users/[^/\s\x00]+/',data), 'Build-user path in '+path
            seen.add(path)
    assert seen==allowed, 'Missing app component: '+str(allowed-seen)
    print('PASS: release archive contains only expected project components:',Path(archive).name)
